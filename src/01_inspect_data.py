import pandas as pd
df = pd.read_csv("data/raw/four_mutations_full_data.csv", usecols=["Variants","HD","Count input","Count selected","Fitness"])
print("shape:", df.shape)
print(df.dtypes.to_string())
print("missing:\n", df.isna().sum().to_string())
print("duplicate Variants:", df.Variants.duplicated().sum())
print("seq length set:", df.Variants.str.len().unique())
print("\nHD counts:\n", df.HD.value_counts().sort_index().to_string())
print("\nFitness describe:\n", df.Fitness.describe().to_string())
print("\nFitness quantiles:\n", df.Fitness.quantile([.01,.1,.25,.5,.75,.9,.99]).to_string())
print("\nFitness == 0:", (df.Fitness==0).sum(), " <0:", (df.Fitness<0).sum(), " >1:", (df.Fitness>1).sum(), " >=0.5:", (df.Fitness>=0.5).sum())
print("\nCount input describe:\n", df["Count input"].describe().to_string())
print("\nreference row:\n", df[df.Variants=="VDGV"].to_string())
import matplotlib; matplotlib.use("Agg")
import matplotlib.pyplot as plt
fig, ax = plt.subplots(1,2, figsize=(10,3.5))
ax[0].hist(df.Fitness, bins=100); ax[0].set_xlabel("Fitness"); ax[0].set_ylabel("count"); ax[0].set_title("Fitness")
ax[1].hist(df.Fitness, bins=100, log=True); ax[1].set_xlabel("Fitness"); ax[1].set_title("Fitness (log count)")
plt.tight_layout(); plt.savefig("outputs/fitness_hist.png", dpi=120)
